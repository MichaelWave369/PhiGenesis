import {createHash,generateKeyPairSync,randomUUID,randomBytes,sign,verify} from 'node:crypto';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,unlinkSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import assert from 'node:assert/strict';
import {openJournal,hash as journalHash} from './phi028-journal.mjs';
import {environment,journalHeads,openWitness,readQuorum} from './phi029-witness.mjs';
import {binding,verifyAssociation,batchCheck} from './phi034-field-gate.mjs';
const canonical=x=>Array.isArray(x)?x.map(canonical):x&&typeof x==='object'?Object.fromEntries(Object.keys(x).sort().map(k=>[k,canonical(x[k])])):x;
const enc=x=>Buffer.from(JSON.stringify(canonical(x))),hash=x=>createHash('sha256').update(enc(x)).digest('hex');
const batch=JSON.parse(readFileSync(process.argv[2],'utf8'));batchCheck(batch,hash);
const roles=['context','operator','evaluator','planner','w0','w1','w2'],ids=roles.slice(4),keys=Object.fromEntries(roles.map(r=>[r,generateKeyPairSync('ed25519')])),config={session:randomUUID(),...Object.fromEntries(roles.map(r=>[r,keys[r].publicKey.export({type:'spki',format:'pem'})]))};
const dir=mkdtempSync(join(tmpdir(),'phi034-')),jdir=join(dir,'journal');mkdirSync(jdir);
for(const r of roles)writeFileSync(join(dir,r+'.pem'),keys[r].privateKey.export({type:'pkcs8',format:'pem'}),{mode:0o600});
for(const id of ids)mkdirSync(join(dir,id));
let checks=0;
try{
 const j=openJournal(jdir,config),wenv=environment(config,j),ws=ids.map(id=>openWitness(join(dir,id),id,wenv)),signers=ids.map(id=>wenv.signer(id,join(dir,id+'.pem')));
 const op=j.signer('operator',join(dir,'operator.pem')),ctxSign=j.signer('context',join(dir,'context.pem'));
 const env={hash,verify:(x,s)=>typeof s==='string'&&verify(null,enc(x),keys.operator.publicKey,Buffer.from(s,'base64'))};
 const sync=()=>{const {heads}=journalHeads(j,jdir);ws.forEach((w,i)=>w.sync(heads,signers[i]))};
 const read=(available=[true,true,true])=>{const challenge=randomBytes(32).toString('hex');return readQuorum(j,jdir,ws.map((w,i)=>available[i]?w.attest(challenge,signers[i]):null),challenge,wenv)};
 const append=e=>{const b=j.load();return j.append(e,op,b.head)};
 const work=(kind,b)=>{const before=j.load();return j.append(j.workEvent(kind,b,op,before),op,before.head)};
 const context=(epoch,world)=>{const body={session:config.session,epoch,world,suite:'phi026-eval-v1',commitment:journalHash([config.session,epoch,world,27186,randomBytes(32).toString('hex')])};return {kind:'context',body,signature:ctxSign('context',body)}};
 sync();append(context(1,'aligned'));
 const b=j.load();work('reserve',{id:1,context:journalHash(b.state.current.state.context),seed:1,policy:'local',artifact:j.env.artifact,budget:16000});sync();
 assert.throws(()=>binding(batch,read(),wenv.identity,env));checks++;
 work('abandon-work',{reservation:j.load().state.pending.hash});
 assert.throws(()=>read());checks++;sync();
 const verified=read(),body=binding(batch,verified,wenv.identity,env),record={body,signature:sign(null,enc(['phi034-association-v1',body]),keys.operator.privateKey).toString('base64')};
 assert.equal(verifyAssociation(batch,verified,wenv.identity,record,env).release,'BLOCKED');checks++;
 assert.equal(verifyAssociation(batch,read([true,true,false]),wenv.identity,record,env).authority,'NONE');checks++;
 assert.throws(()=>read([true,false,false]));checks++;
 const changed=structuredClone(batch);changed.rows[0].review.receipts[3].execution_authority=true;
 assert.throws(()=>verifyAssociation(changed,read(),wenv.identity,record,env));checks++;
 assert.throws(()=>verifyAssociation(batch,read(),wenv.identity,{...record,signature:'bad'},env));checks++;
 const tail=join(jdir,'002.json'),bytes=readFileSync(tail);unlinkSync(tail);
 assert.throws(()=>read());checks++;writeFileSync(tail,bytes);
 append(context(2,'shifted'));sync();
 assert.throws(()=>verifyAssociation(batch,read(),wenv.identity,record,env));checks++;
 console.log(JSON.stringify({status:'passed',checks,reviews:batch.rows.length,association:record.body,release:'BLOCKED',authority:'NONE',blockers:verifyAssociation(batch,verified,wenv.identity,record,env).blockers}));
}finally{rmSync(dir,{recursive:true,force:true})}
